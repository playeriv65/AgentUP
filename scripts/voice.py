import asyncio
from pathlib import Path
import edge_tts

texts = [
'矩阵乘法，可以从四种视角理解。我们用同一组矩阵，依次看向量内积、向量外积、行空间的重新组合，以及列空间的重新组合。',
'第一种，向量内积。结果的每一个元素，来自 A 的一行与 B 的一列。对应位置相乘，再把乘积相加。比如左上角，一乘一，加二乘零，加一乘二，等于三。右上角得到五。第二行的两个内积，分别得到四和五。每次内积生成一个数，四个数组成结果矩阵。',
'第二种，向量外积。取 A 的第一列，乘 B 的第一行，得到一个完整的二乘二矩阵。再取第二列和第二行，生成第二个矩阵。第三列与第三行，生成第三个矩阵。这里的外积是列向量乘行向量，不是三维叉积。把三个矩阵对应位置相加，就得到同一个结果。',
'第三种，行空间的重新组合。把 B 的三行看成三个向量。A 的第一行，一、二、一，就是组合权重。第一行向量，加上两倍第二行，再加第三行，得到三、五。箭头先缩放，再首尾相接。A 的第二行给出另一组权重，二、零、一，组合得到四、五。因此结果的每一行，都仍在 B 的行空间中。',
'第四种，列空间的重新组合。这次把 A 的三列看成三个向量。B 的第一列，一、零、二，是组合权重。第一列向量，加上零倍第二列，再加两倍第三列，得到三、四。B 的第二列，二、一、一，组合得到五、五。因此结果的每一列，都仍在 A 的列空间中。注意两种组合的权重来自不同的一侧。',
'四种视角，算的是同一个矩阵。内积一次生成一个元素，外积一次生成一个矩阵再累加。行组合一次生成一行，列组合一次生成一列。把这四种视角连接起来，就能更灵活地理解矩阵乘法。'
]
out=Path(__file__).resolve().parents[1] / 'remotion/public'
out.mkdir(parents=True, exist_ok=True)
async def main():
    for i,t in enumerate(texts):
        await edge_tts.Communicate(t,'zh-CN-YunxiNeural',rate='+12%').save(str(out/f'voice-{i}.mp3'))
        print(f'voice {i} done',flush=True)
asyncio.run(main())
